#!/usr/bin/env node
/**
 * Regenerate references/ from the engine bundle's own agent exports.
 *
 * Usage:
 *     node extract-references.mjs [--bundle <path-or-url>]
 *
 * The action vocabulary's single source of truth is the engine bundle
 * (`ACTIONS_SCHEMA`, `ACTION_OPS`, `AGENT_GUIDE` — the surface its test
 * suite freezes). This script snapshots those exports verbatim into
 * references/actions.md and references/guide.md, stamped with the bundle
 * hash, so the skill never hand-copies (and silently forks) the contract.
 * Maintainer tool — run it whenever a new engine build ships.
 */

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile, unlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REFERENCES_DIR = join(__dirname, '..', 'references');
const DEFAULT_BUNDLE = 'https://s.show/statics/sshow/index.min.js';

const fail = (message) => {
    console.error(`  ✗ ${message}`);
    process.exit(1);
};

const loadBundle = async (bundle) => {
    if (bundle.startsWith('https://') || bundle.startsWith('http://')) {
        const response = await fetch(bundle).catch((error) => fail(`bundle fetch failed: ${bundle} — ${error.message}`));
        if (!response.ok) fail(`bundle fetch failed: ${bundle} — HTTP ${response.status}`);
        return Buffer.from(await response.arrayBuffer());
    }
    return readFile(resolve(bundle)).catch(() => fail(`bundle not found: ${resolve(bundle)}`));
};

const main = async () => {
    const { values } = parseArgs({ options: { bundle: { type: 'string', default: DEFAULT_BUNDLE } } });

    const bytes = await loadBundle(values.bundle);
    const stamp = createHash('md5').update(bytes).digest('hex').slice(0, 8);

    // Import via a temp .mjs copy so the bundle parses as ESM regardless of
    // where it was downloaded (module type is decided by file context).
    const temp = join(tmpdir(), `sshow-bundle-${stamp}.mjs`);
    await writeFile(temp, bytes);
    let agent;
    try {
        agent = await import(pathToFileURL(temp).href);
    } catch (error) {
        fail(`bundle import failed: ${error.message}`);
    } finally {
        await unlink(temp).catch(() => {});
    }

    const { ACTIONS_SCHEMA, ACTION_OPS, AGENT_GUIDE } = agent;
    if (!ACTIONS_SCHEMA || !ACTION_OPS || !AGENT_GUIDE) {
        fail('bundle is missing agent exports (ACTIONS_SCHEMA / ACTION_OPS / AGENT_GUIDE)');
    }

    await mkdir(REFERENCES_DIR, { recursive: true });
    const date = new Date().toISOString().slice(0, 10);
    const header = (title) => [
        `<!-- GENERATED by scripts/extract-references.mjs — do not edit by hand.`,
        `     Engine bundle ${stamp} · extracted ${date}.`,
        `     Regenerate: node scripts/extract-references.mjs [--bundle <path-or-url>] -->`,
        '',
        `# ${title}`,
        ''
    ].join('\n');

    await writeFile(join(REFERENCES_DIR, 'actions.md'), [
        header('Action schema (`apply_actions`)'),
        'The machine contract for the action document: every op and the exact',
        'parameter shape the engine accepts. Values, units, and recipes live in',
        '[guide.md](guide.md).',
        '',
        `## Ops (${ACTION_OPS.length})`,
        '',
        ...ACTION_OPS.map((op) => `- \`${op}\``),
        '',
        '## Schema',
        '',
        '```json',
        JSON.stringify(ACTIONS_SCHEMA, null, 2),
        '```',
        ''
    ].join('\n'));

    await writeFile(join(REFERENCES_DIR, 'guide.md'), [
        header('Engine guide (AGENT_GUIDE)'),
        'The engine\'s own authoring reference — the same text its AI panel and',
        'MCP server serve. Read the sections relevant to the current document.',
        '',
        AGENT_GUIDE.trim(),
        ''
    ].join('\n'));

    console.log(`  ✓ references/actions.md, references/guide.md (bundle ${stamp})`);
};

main();
